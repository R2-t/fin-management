use serde::{Deserialize, Serialize};

/// One dated movement of money for one Wallet.
///
/// A Wallet's balance is the sum of its entries (ADR-0004). Entries are
/// append-only: they are never edited, only superseded by a correcting entry.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct LedgerEntry {
    pub id: uuid::Uuid,
    pub user_id: uuid::Uuid,
    pub wallet_id: uuid::Uuid,
    pub occurred_at: chrono::DateTime<chrono::Utc>,
    /// Signed minor units: credits positive, debits negative.
    pub amount_minor: i64,
    pub currency: String,
    pub kind: LedgerKind,
    pub purchase_id: Option<uuid::Uuid>,
    pub transfer_id: Option<uuid::Uuid>,
    /// When this entry was superseded by a correction. `None` means it is still
    /// active and counts toward the balance.
    pub superseded_at: Option<chrono::DateTime<chrono::Utc>>,
    pub created_at: chrono::DateTime<chrono::Utc>,
}

/// What caused a ledger entry. Transfer legs are generated by a `transfer`
/// record and are never edited directly (ADR-0003).
#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum LedgerKind {
    /// The balance the wallet started with.
    OpeningBalance,
    /// A purchase debit.
    Purchase,
    /// An income credit.
    Income,
    /// One leg of a transfer.
    Transfer,
    /// A manual correction by the user.
    Adjustment,
}

impl LedgerKind {
    pub fn as_str(self) -> &'static str {
        match self {
            LedgerKind::OpeningBalance => "opening_balance",
            LedgerKind::Purchase => "purchase",
            LedgerKind::Income => "income",
            LedgerKind::Transfer => "transfer",
            LedgerKind::Adjustment => "adjustment",
        }
    }

    pub fn parse(raw: &str) -> Option<Self> {
        match raw {
            "opening_balance" => Some(LedgerKind::OpeningBalance),
            "purchase" => Some(LedgerKind::Purchase),
            "income" => Some(LedgerKind::Income),
            "transfer" => Some(LedgerKind::Transfer),
            "adjustment" => Some(LedgerKind::Adjustment),
            _ => None,
        }
    }
}

/// A Wallet's balance: the sum of its ledger entries, with the currency they
/// are denominated in.
#[derive(Debug, Clone, Serialize)]
pub struct WalletBalance {
    pub wallet_id: uuid::Uuid,
    pub currency: String,
    /// Signed. Negative means the wallet is overdrawn.
    pub balance_minor: i64,
    pub entry_count: i64,
}
