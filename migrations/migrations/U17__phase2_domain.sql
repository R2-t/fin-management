-- Phase 2: the domain tables the forecast needs.
--
-- The ledger comes first because everything else derives from it: a budget's
-- burn is spend, an income schedule's receipt is a ledger credit, and runway
-- starts from a balance that is the sum of ledger entries (ADR-0004).
--
-- Every table is per-user. Money is always in integer minor units of a single
-- currency, never summed across currencies (ADR-0002).

-- ---------------------------------------------------------------------------
-- Ledger
-- ---------------------------------------------------------------------------

-- Append-only. A Wallet's balance is the SUM of its entries; there is no
-- mutable balance column, so a balance can always be reconciled against the
-- movements that produced it (ADR-0004).
--
-- `kind` is closed: an entry is an opening balance, a purchase debit, an
-- income credit, a transfer leg, or an adjustment. Transfer legs are never
-- edited directly -- they are generated by a `transfer` record (ADR-0003).
CREATE TABLE IF NOT EXISTS ledger_entry (
    id           UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id      UUID NOT NULL,
    wallet_id    UUID NOT NULL REFERENCES wallet(id),
    occurred_at  TIMESTAMPTZ NOT NULL,
    -- Signed: credits are positive, debits negative. Minor units.
    amount_minor BIGINT NOT NULL,
    currency     CHAR(3) NOT NULL,
    kind         VARCHAR NOT NULL CHECK (kind IN (
        'opening_balance', 'purchase', 'income', 'transfer', 'adjustment'
    )),
    -- The record that generated this entry, when there is one. A purchase debit
    -- points at its Purchase; a transfer leg points at its Transfer.
    purchase_id  UUID REFERENCES purchase(id),
    transfer_id  UUID,
    -- When this entry was superseded by a correction. NULL means the entry is
    -- still active. The balance sums active entries only.
    superseded_at TIMESTAMPTZ,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- Balance reads are "sum for this wallet", and the projection of a purchase
-- needs to find a wallet's entries by date.
CREATE INDEX IF NOT EXISTS ledger_entry_wallet_idx
    ON ledger_entry (wallet_id, occurred_at);

CREATE INDEX IF NOT EXISTS ledger_entry_user_idx
    ON ledger_entry (user_id, occurred_at DESC);

-- A Purchase produces exactly one *active* debit. Enforced here rather than
-- in code so that a replayed event cannot double-charge a wallet.
--
-- A correction (an edited amount, a corrected rate) supersedes the prior debit
-- rather than editing it: the old entry is closed and a new one is written.
-- The partial unique index covers only the entries that are still active, so
-- the history of corrections is preserved while the current debit is still
-- guaranteed unique.
CREATE UNIQUE INDEX IF NOT EXISTS ledger_entry_purchase_active_unique
    ON ledger_entry (purchase_id)
    WHERE purchase_id IS NOT NULL AND superseded_at IS NULL;

-- ---------------------------------------------------------------------------
-- Transfer
-- ---------------------------------------------------------------------------

-- A first-class record that generates two ledger legs (ADR-0003). Storing it
-- as its own object is what makes correcting a mistaken transfer coherent:
-- the legs are regenerated, not hunted for.
CREATE TABLE IF NOT EXISTS transfer (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id            UUID NOT NULL,
    from_wallet_id     UUID NOT NULL REFERENCES wallet(id),
    to_wallet_id       UUID NOT NULL REFERENCES wallet(id),
    occurred_at        TIMESTAMPTZ NOT NULL,
    amount_minor       BIGINT NOT NULL CHECK (amount_minor > 0),
    currency           CHAR(3) NOT NULL,
    description        TEXT,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at         TIMESTAMPTZ,
    -- A transfer between two of the user's own wallets is not a movement of
    -- value; it cannot be to the same wallet.
    CONSTRAINT transfer_distinct_wallets CHECK (from_wallet_id <> to_wallet_id)
);

CREATE INDEX IF NOT EXISTS transfer_user_idx
    ON transfer (user_id, occurred_at DESC);

-- The legs a transfer generates. `transfer_id` is set here but has no foreign
-- key to `transfer` yet: the table is created in the same migration, and
-- adding the FK would couple the ledger to the transfer lifecycle for no
-- benefit. Legs are deleted and regenerated with their transfer, never edited.

-- ---------------------------------------------------------------------------
-- Budget
-- ---------------------------------------------------------------------------

-- A spending limit for one Category within one Wallet, over a Budget period
-- (see GLOSSARY.md).
--
-- `category_id IS NULL` means the limit covers the whole Wallet rather than
-- one category. The Wallet scope is what makes "budget in one currency" true:
-- a budget's currency is the Wallet's currency, so a limit is never compared
-- against a mixed-currency total (ADR-0002).
CREATE TABLE IF NOT EXISTS budget (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        UUID NOT NULL,
    wallet_id      UUID NOT NULL REFERENCES wallet(id),
    category_id    INTEGER REFERENCES category(id),
    name           VARCHAR NOT NULL,
    -- The limit for one period, in minor units of the Wallet's currency.
    amount_minor   BIGINT NOT NULL CHECK (amount_minor > 0),
    -- How often the budget recurs: 'weekly' | 'monthly' | 'yearly'.
    cadence        VARCHAR NOT NULL CHECK (cadence IN ('weekly', 'monthly', 'yearly')),
    -- The day of the month the period resets on, for a monthly cadence: 1 for
    -- a calendar month, 15 for someone paid on the 15th, -1 for the last day
    -- of the month. Ignored by the other cadences.
    reset_day      SMALLINT NOT NULL DEFAULT 1,
    -- The first period's start date. The period runs from here for one cadence
    -- step; occurrences are materialised as `budget_period` rows.
    starts_on      DATE NOT NULL,
    -- An end date stops the budget; NULL means it recurs indefinitely.
    ends_on        DATE,
    -- Whether unspent limit carries into the next period.
    rollover_unspent BOOLEAN NOT NULL DEFAULT TRUE,
    -- Whether an overspend carries into the next period, so the next period
    -- starts in the hole rather than being forgiven by the reset.
    carry_overspend  BOOLEAN NOT NULL DEFAULT TRUE,
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT budget_period_order CHECK (ends_on IS NULL OR ends_on >= starts_on),
    -- A reset day outside the calendar is rejected. -1 means the last day of
    -- the month, which is expressed as -1 and not as 31, because months have
    -- different lengths.
    CONSTRAINT budget_reset_day_check CHECK (reset_day >= -1 AND reset_day <= 31)
);

CREATE INDEX IF NOT EXISTS budget_user_idx
    ON budget (user_id, active)
    WHERE deleted_at IS NULL;

-- One materialised occurrence of a budget template, holding the limit that
-- actually applies to that period. Editing a period does not change the
-- template (GLOSSARY.md).
CREATE TABLE IF NOT EXISTS budget_period (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    budget_id      UUID NOT NULL REFERENCES budget(id) ON DELETE CASCADE,
    user_id        UUID NOT NULL,
    -- The limit for this period, in minor units of the Wallet's currency.
    --
    -- This is the EFFECTIVE limit: the template's amount, adjusted by a carry
    -- that lowers it, or replaced by a user edit. Nothing automatically RAISES
    -- it (D35): unspent money is reported as `unspent_minor` instead, because
    -- the user may be deliberately saving it (D34).
    --
    -- May be zero or negative when a carried overspend exceeds the template
    -- amount: the user is 200 under a 500 limit, so the next period starts at
    -- 300, and 700 over a 500 limit leaves the next period at -200. A negative
    -- limit means the user has already overspent by that much in the new
    -- period.
    amount_minor   BIGINT NOT NULL,
    -- The limit the template itself specifies, kept so an edited period can be
    -- distinguished from a carried one, and so the effective limit can be
    -- explained without re-deriving it.
    template_minor BIGINT NOT NULL CHECK (template_minor > 0),
    -- Money left over in this period. Reported, never added to the next
    -- period's limit (D34).
    unspent_minor   BIGINT NOT NULL DEFAULT 0,
    period_start   DATE NOT NULL,
    period_end     DATE NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT budget_period_order CHECK (period_end >= period_start),
    CONSTRAINT budget_period_unique UNIQUE (budget_id, period_start)
);

CREATE INDEX IF NOT EXISTS budget_period_user_idx
    ON budget_period (user_id, period_start DESC);

-- ---------------------------------------------------------------------------
-- Income
-- ---------------------------------------------------------------------------

-- An expectation that money will arrive on a cadence. It is NOT money until an
-- occurrence is received (ADR-0008): booking it on the scheduled date would
-- invent money that may never arrive.
CREATE TABLE IF NOT EXISTS income_schedule (
    id             UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id        UUID NOT NULL,
    name           VARCHAR NOT NULL,
    -- The wallets an occurrence is credited to. One schedule may split across
    -- several wallets, as one intentional act (ADR-0003).
    amount_minor   BIGINT NOT NULL CHECK (amount_minor > 0),
    currency       CHAR(3) NOT NULL,
    -- How often it arrives: 'weekly' | 'biweekly' | 'semimonthly' | 'monthly'.
    cadence        VARCHAR NOT NULL CHECK (cadence IN (
        'weekly', 'biweekly', 'semimonthly', 'monthly'
    )),
    -- The first expected date. Later occurrences are derived from it.
    starts_on      DATE NOT NULL,
    ends_on        DATE,
    active         BOOLEAN NOT NULL DEFAULT TRUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at     TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at     TIMESTAMPTZ,
    CONSTRAINT income_period_order CHECK (ends_on IS NULL OR ends_on >= starts_on)
);

CREATE INDEX IF NOT EXISTS income_schedule_user_idx
    ON income_schedule (user_id, active)
    WHERE deleted_at IS NULL;

-- The split of one income occurrence across wallets. Kept with the schedule
-- because it is part of the expectation, not of the receipt.
CREATE TABLE IF NOT EXISTS income_allocation (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    income_schedule_id UUID NOT NULL REFERENCES income_schedule(id) ON DELETE CASCADE,
    user_id            UUID NOT NULL,
    wallet_id          UUID NOT NULL REFERENCES wallet(id),
    amount_minor       BIGINT NOT NULL CHECK (amount_minor > 0),
    currency           CHAR(3) NOT NULL
);

CREATE INDEX IF NOT EXISTS income_allocation_schedule_idx
    ON income_allocation (income_schedule_id);

-- A recorded occurrence: the point where an expectation becomes money
-- (ADR-0008). The ledger credit entries are written in the same transaction.
CREATE TABLE IF NOT EXISTS income_receipt (
    id                 UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    income_schedule_id UUID NOT NULL REFERENCES income_schedule(id),
    user_id            UUID NOT NULL,
    occurred_at        TIMESTAMPTZ NOT NULL,
    amount_minor       BIGINT NOT NULL CHECK (amount_minor > 0),
    currency           CHAR(3) NOT NULL,
    created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS income_receipt_user_idx
    ON income_receipt (user_id, occurred_at DESC);

-- ---------------------------------------------------------------------------
-- Recurring rule
-- ---------------------------------------------------------------------------

-- A declared recurring commitment: a subscription the user expects to keep
-- paying. Forecasts subtract these; the ledger is not written until the user
-- records the actual purchase.
CREATE TABLE IF NOT EXISTS recurring_rule (
    id              UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id         UUID NOT NULL,
    wallet_id       UUID NOT NULL REFERENCES wallet(id),
    merchant_id     UUID REFERENCES merchant(id),
    category_id     INTEGER REFERENCES category(id),
    name            VARCHAR NOT NULL,
    amount_minor    BIGINT NOT NULL CHECK (amount_minor > 0),
    currency        CHAR(3) NOT NULL,
    cadence         VARCHAR NOT NULL CHECK (cadence IN (
        'weekly', 'biweekly', 'semimonthly', 'monthly', 'yearly'
    )),
    starts_on       DATE NOT NULL,
    ends_on         DATE,
    -- 'active' | 'cancelled' | 'ended'. A cancelled rule stops being forecast.
    status          VARCHAR NOT NULL DEFAULT 'active'
                    CHECK (status IN ('active', 'cancelled', 'ended')),
    created_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at      TIMESTAMPTZ,
    CONSTRAINT recurring_period_order CHECK (ends_on IS NULL OR ends_on >= starts_on)
);

CREATE INDEX IF NOT EXISTS recurring_rule_user_idx
    ON recurring_rule (user_id, status)
    WHERE deleted_at IS NULL;

-- ---------------------------------------------------------------------------
-- Forecast
-- ---------------------------------------------------------------------------

-- A generated forecast, versioned so it can be evaluated and compared
-- (analytics-investigation §4.4). `model_version` names the algorithm, so a
-- result can be reproduced or superseded.
CREATE TABLE IF NOT EXISTS forecast (
    id            UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    user_id       UUID NOT NULL,
    wallet_id     UUID NOT NULL REFERENCES wallet(id),
    kind          VARCHAR NOT NULL CHECK (kind IN (
        'budget_overspend', 'cash_runway'
    )),
    generated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    horizon_days  INT NOT NULL,
    -- The result and the assumptions it was made under. The assumptions are
    -- stored with the result so a stale forecast explains itself.
    result        JSONB NOT NULL,
    assumptions   JSONB NOT NULL,
    model_version VARCHAR NOT NULL
);

CREATE INDEX IF NOT EXISTS forecast_user_idx
    ON forecast (user_id, generated_at DESC);
